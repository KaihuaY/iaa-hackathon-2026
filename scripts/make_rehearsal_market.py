"""Build a synthetic 'emerging market' dataset from Part 1 for the new-market dress rehearsal.

  python -P -E scripts/make_rehearsal_market.py [--src data/raw/public] [--dst data/rehearsal]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MONEY = ["written_premium", "sum_insured", "paid_to_date", "incurred_to_date", "recoveries"]
DATE_COLS = ["period_start", "period_end", "loss_date", "report_date"]
FX = 50.0
SHIFT = pd.DateOffset(years=-2)

README = """# Rehearsal market (synthetic, derived from Part 1)

Generated by scripts/make_rehearsal_market.py. Transformations:
- Lines: motor and buildings only; contents policies/test tables not written; contents claims removed.
- Years shifted by -2 (period_start, period_end, loss_date, report_date; weather.year): train 2019-2022, test 2023.
- Currency x50: written_premium, sum_insured, paid_to_date, incurred_to_date, recoveries.
- motor: driver_age renamed to age_driver (policies and test).
- previous_insurer dropped (customers).
- customer_id zero-padded to 8 characters in every table (no leading-zero defect).
- Last year left as is (no immature-year adjustment; spec uses immature_years=()).
- Everything else unchanged (customers, addresses, weather rows, claims of motor/buildings, sample_submission restricted to motor/buildings test rows).
"""


def shift_dates(s: pd.Series) -> pd.Series:
    return (pd.to_datetime(s) + SHIFT).dt.date


def transform(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    for c in DATE_COLS:
        if c in df:
            df[c] = shift_dates(df[c])
    for c in MONEY:
        if c in df:
            df[c] = df[c] * FX
    if "customer_id" in df:
        df["customer_id"] = df["customer_id"].astype(str).str.zfill(8)
    if "driver_age" in df:
        df = df.rename(columns={"driver_age": "age_driver"})
    return df.drop(columns=[c for c in ["previous_insurer"] if c in df])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "data" / "raw" / "public"))
    ap.add_argument("--dst", default=str(ROOT / "data" / "rehearsal"))
    a = ap.parse_args()
    src, dst = Path(a.src), Path(a.dst)
    dst.mkdir(parents=True, exist_ok=True)
    rd = lambda n: pd.read_parquet(src / f"{n}.parquet")
    out = {}
    for n in ["policies_motor", "policies_buildings", "test_motor", "test_buildings", "customers", "addresses"]:
        out[n] = transform(rd(n))
    cl = rd("claims")
    out["claims"] = transform(cl[cl["line"] != "contents"].reset_index(drop=True))
    w = rd("weather")
    w["year"] = w["year"] - 2
    out["weather"] = w
    ss = rd("sample_submission")
    ids = set(out["test_motor"]["row_id"]) | set(out["test_buildings"]["row_id"])
    out["sample_submission"] = ss[ss["row_id"].isin(ids)].reset_index(drop=True)
    for n, d in out.items():
        d.to_parquet(dst / f"{n}.parquet", index=False)
        print(n, d.shape)
    (dst / "README.md").write_text(README, encoding="utf-8")


if __name__ == "__main__":
    main()
